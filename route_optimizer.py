"""Member 5: shortest-walking route optimizer for Member 4's QAOA candidates.

Member 4 returns each candidate as a dictionary with a ``selected_ids`` list.
Pass that list directly to ``optimize_route``. No entrance or exit is included.
Walking times are minutes, as loaded by data_adapter.build_walking_matrix.
"""

from itertools import permutations


def calculate_walking_time(route, walking_matrix):
    """Return the total walking minutes between consecutive rides in route.

    Args:
        route (list[str] | tuple[str, ...]): A visit order, e.g. ["R_1", "R_3"].
        walking_matrix (dict): Nested dictionary: matrix[from_id][to_id].

    Returns:
        float: Total walking minutes (0 for zero or one ride).
    """
    total_time = 0.0
    for index in range(len(route) - 1):
        current_ride = route[index]
        next_ride = route[index + 1]
        try:
            minutes = walking_matrix[current_ride][next_ride]
        except KeyError as error:
            raise ValueError(
                f"Missing walking time from {current_ride} to {next_ride}"
            ) from error
        total_time += minutes
    return float(total_time)


def optimize_route(selected_rides, walking_matrix, start_location=None):
    """Find the minimum-walking-time ordering of a QAOA-selected ride set.

    Args:
        selected_rides (list[str]): Member 4 candidate['selected_ids'].
        walking_matrix (dict): Nested walking-time dictionary (minutes).

    Returns:
        tuple[list[str], float]: (best_route, walking_time_minutes).

    Notes:
        No entrance/exit is considered. If two routes have equal walking
        times, the first one generated by permutations is retained.
        This minimizes walking time, not necessarily total time when queue
        lengths depend on arrival times.
    """
    if len(selected_rides) != len(set(selected_rides)):
        raise ValueError("selected_rides contains duplicate ride IDs")

    for ride_id in selected_rides:
        if ride_id not in walking_matrix:
            raise ValueError(f"Unknown ride ID: {ride_id}")

    if start_location is not None and start_location not in walking_matrix:
        raise ValueError(f"Unknown starting location: {start_location}")
    if not selected_rides:
        return [], 0.0

    best_route = []
    best_time = float("inf")

    for order in permutations(selected_rides):
        walking_time = calculate_walking_time(order, walking_matrix)
        if start_location is not None:
            walking_time += walking_matrix[start_location][order[0]]
        if walking_time < best_time:
            best_time = walking_time
            best_route = list(order)

    return best_route, best_time


def optimize_route_total_time(selected_rides, walking_matrix, ride_data,
                              queue_data, start_time, time_budget,
                              start_location=None):
    """Find the FASTEST feasible order using arrival-time-dependent queues.

    Unlike optimize_route(), compares walking + observed queue + ride durations
    at each stop. Returns (route, full_time_info), or None if no order fits.
    Uses depth-first enumeration with safe pruning; intended for <=8 rides.
    """
    from datetime import datetime, timedelta
    from time_calculator import get_queue_time, calculate_total_time

    if not isinstance(start_time, datetime):
        raise TypeError('start_time must be datetime')
    if time_budget < 0:
        raise ValueError('time_budget must be nonnegative')
    rides = list(selected_rides)
    if len(rides) != len(set(rides)):
        raise ValueError('Duplicate ride IDs in candidate')
    if not rides:
        return None
    for ride in rides:
        if ride not in walking_matrix or ride not in ride_data:
            raise ValueError(f'Unknown ride ID: {ride}')
    if start_location is not None and start_location not in walking_matrix:
        raise ValueError(f'Unknown starting location: {start_location}')

    best_route = None
    best_total = float('inf')
    # Time lookup caching helps when many orders revisit the same partial plan.
    wait_cache = {}

    def walk_minutes(previous, ride):
        if previous is None:
            return 0.0
        try:
            minutes = float(walking_matrix[previous][ride])
        except KeyError as exc:
            raise ValueError(f'Missing walking time: {previous} -> {ride}') from exc
        if not 0 <= minutes < float('inf'):
            raise ValueError(f'Invalid walking minutes: {previous} -> {ride}')
        return minutes

    def dfs(prefix, unused, previous, now, elapsed):
        nonlocal best_route, best_total
        if not unused:
            if elapsed < best_total:
                best_total = elapsed
                best_route = prefix[:]
            return
        for ride in unused:
            walking = walk_minutes(previous, ride)
            arrival = now + timedelta(minutes=walking)
            key = (ride, arrival)
            if key not in wait_cache:
                try:
                    wait_cache[key] = get_queue_time(ride, arrival, queue_data)
                except ValueError as exc:
                    # A route that runs beyond the recorded date cannot be scored.
                    if str(exc).startswith('No queue data for '):
                        wait_cache[key] = None
                    else:
                        raise
            wait = wait_cache[key]
            if wait is None:
                continue
            duration = float(ride_data[ride]['duration'])
            if not (0 <= wait < float('inf') and 0 <= duration < float('inf')):
                raise ValueError(f'Invalid duration or queue time for {ride}')
            next_elapsed = elapsed + walking + wait + duration
            # With nonnegative costs, this can never improve the best route.
            if next_elapsed > time_budget or next_elapsed >= best_total:
                continue
            dfs(prefix + [ride], [r for r in unused if r != ride], ride,
                arrival + timedelta(minutes=wait + duration), next_elapsed)

    dfs([], rides, start_location, start_time, 0.0)
    if best_route is None:
        return None
    # Reuse the project's existing timeline formatter for UI compatibility.
    time_info = calculate_total_time(best_route, ride_data, walking_matrix,
                                     queue_data, start_time,
                                     start_location=start_location)
    return best_route, time_info
